"""Темы канала и автоматическая разметка по названию видео."""

TOPICS = ["Тревога", "Панические атаки", "Невроз", "ВСД", "Самопомощь", "Работа с мыслями"]
DEFAULT_TOPIC = "Самопомощь"

# Порядок важен: более узкие темы проверяются раньше.
KEYWORDS = [
    ("Панические атаки", ["паническ", "паник", " па ", "#па"]),
    ("ВСД", ["всд", "вегет", "дистони", "сердцебиени", "головокружени", "давлени"]),
    ("Невроз", ["невроз", "окр", "навязчив", "ипохондр", "дереализ", "деперсонал"]),
    ("Работа с мыслями", ["мысл", "мышлени", "убеждени", "катастроф", "руминац"]),
    ("Тревога", ["тревог", "тревож", "страх", "беспокой", "волнени"]),
    ("Самопомощь", ["упражнени", "техник", "дыхани", "самопомощ", "как справиться", "что делать"]),
]


def classify(title):
    text = f" {(title or '').lower()} "
    for topic, words in KEYWORDS:
        if any(word in text for word in words):
            return topic
    return DEFAULT_TOPIC
